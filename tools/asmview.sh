#!/usr/bin/env bash
# asmview.sh TARGET MODULE UNIT [FUNC...]: a unit's (or some functions')
# disassembly without the address/encoding comments, plus its strings.
cd "$(dirname "$0")/.."
t=$1 m=$2 u=$3; shift 3
d=tmp/asm/$t/$m/nonmatchings/$u
fs=("$@"); [ ${#fs[@]} -eq 0 ] && fs=($(ls $d/*.s 2>/dev/null | xargs -n1 basename | sed 's/\.s$//'))
for f in "${fs[@]}"; do
  echo "### $f"
  grep -vE '^\s*$|^\.(set|section|align)|enddlabel|^nonmatching|^dlabel|^endlabel|Generated by|^\s*/\* [0-9A-F]+ \*/$' $d/$f.s \
    | sed -E 's#/\* [0-9A-F]+ [0-9A-F]+ [0-9A-F]+ \*/ +##; s#^\s*/\* [0-9A-F]+ ([0-9A-F]+) \*/ #\1: #'
done
