void DrawDragon(int tex)
{
	ScePspFVector3	vec;
	int				i;

	sceGumPushMatrix();
	if (!tex) {
		sceGuColor(GRAY);
		sceGuDisable(SCEGU_TEXTURE);
	}
	else {
		sceGuEnable(SCEGU_TEXTURE);
		sceGuColor(WHITE);
		sceGuTexMode(SCEGU_PFIDX8, 0, SCEGU_SINGLE_CLUT, SCEGU_TEXBUF_NORMAL);
		sceGuTexFunc(SCEGU_TEX_MODULATE,SCEGU_RGB);
		sceGuClutMode(SCEGU_PF5551, 0, 0xff, 0);
		sceGuClutLoad(16, (void *)clut_face);
		sceGuTexImage(0, 64, 64, 64, (void *)chr_face);
		sceGuTexScale(0.333333f, 0.333333f);
		sceGuTexOffset(0.0f, 0.0f);
	}
	sceGumDrawSpline(SCEGU_VERTEX_FLOAT, 6, 6,
					SCEGU_OPEN_OPEN, SCEGU_OPEN_OPEN, 0, (void *)face);

	if (tex) {
		sceGuDisable(SCEGU_TEXTURE);
		sceGuColor(SKINCOLOR);
	}
	sceGumDrawSpline(SCEGU_VERTEX_FLOAT, 6, 5,
					SCEGU_OPEN_OPEN, SCEGU_OPEN_OPEN, 0, (void *)head);
	sceGumDrawSpline(SCEGU_VERTEX_FLOAT, 6, 4,
					SCEGU_OPEN_OPEN, SCEGU_OPEN_OPEN, 0, (void *)horn1);
	sceGumDrawSpline(SCEGU_VERTEX_FLOAT, 5, 4,
					SCEGU_OPEN_OPEN, SCEGU_OPEN_OPEN, 0, (void *)horn2);

	for (i=0; i<2; i++) {

          vec.x=1.0f-2.0f*(float)i, vec.y=1.0f, vec.z=1.0f;
		sceGumScale(&vec);
          
		if (tex) {
			sceGuEnable(SCEGU_TEXTURE);
			sceGuColor(WHITE);
			sceGuTexMode(SCEGU_PFIDX4, 0, SCEGU_SINGLE_CLUT, SCEGU_TEXBUF_NORMAL);
			sceGuClutMode(SCEGU_PF5551, 0, 0xff, 0);
			sceGuClutLoad(1, (void *)clut_body);
			sceGuTexImage(0, 32, 32, 32, (void *)chr_body);
			sceGuTexScale(0.166667f, 0.980392f);
			sceGuTexOffset(0.0f, 0.009804f);
		}
		sceGumDrawSpline(SCEGU_VERTEX_FLOAT, 9, 4,
						SCEGU_OPEN_OPEN, SCEGU_OPEN_OPEN, 0, (void *)body);

		if (tex) {
			sceGuDisable(SCEGU_TEXTURE);
			sceGuColor(SKINCOLOR);
		}
		sceGumDrawBezier(SCEGU_VERTEX_FLOAT, 4, 4, 0, (void *)l_hand);
		sceGumDrawSpline(SCEGU_VERTEX_FLOAT, 5, 4,
						SCEGU_OPEN_OPEN, SCEGU_OPEN_OPEN, 0, (void *)l_foot);
		sceGumDrawBezier(SCEGU_VERTEX_FLOAT, 4, 4, 0, (void *)l_leg1);
		sceGumDrawSpline(SCEGU_VERTEX_FLOAT, 5, 4,
						SCEGU_OPEN_OPEN, SCEGU_OPEN_OPEN, 0, (void *)l_leg2);
		sceGumDrawSpline(SCEGU_VERTEX_FLOAT, 5, 4,
						SCEGU_OPEN_OPEN, SCEGU_OPEN_OPEN, 0, (void *)r_foot);
		sceGumDrawBezier(SCEGU_VERTEX_FLOAT, 4, 4, 0, (void *)r_leg1);
		sceGumDrawSpline(SCEGU_VERTEX_FLOAT, 5, 4,
						SCEGU_OPEN_OPEN, SCEGU_OPEN_OPEN, 0, (void *)r_leg2);
		sceGumDrawBezier(SCEGU_VERTEX_FLOAT, 4, 4, 0, (void *)wing1);
		sceGumDrawBezier(SCEGU_VERTEX_FLOAT, 4, 4, 0, (void *)wing2);

		if (tex) {
			sceGuEnable(SCEGU_TEXTURE);
			sceGuColor(WHITE);
			sceGuTexMode(SCEGU_PF5551, 0, SCEGU_SINGLE_CLUT, SCEGU_TEXBUF_NORMAL);
			sceGuTexImage(0, 2, 2, 8, (void *)chr_wing);
			sceGuTexScale(1.0f, 1.0f);
			sceGuTexOffset(0.0f, 0.0f);
		}
		sceGumDrawBezier(SCEGU_VERTEX_FLOAT, 4, 4, 0, (void *)wing_skin);
	}

	sceGumPopMatrix();
	sceGuColor(WHITE);
}

